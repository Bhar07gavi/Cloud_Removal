"""PyTorch Dataset for loading preprocessed cloudy/ground-truth patch pairs
from CSV manifests generated by the preprocessing pipeline.
"""

import csv
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset

__all__ = ["CloudRemovalDataset", "build_dataloader", "build_dataloaders"]


class CloudRemovalDataset(Dataset):
    """Dataset that loads pre-tiled, pre-normalized .npy cloudy/GT patch pairs.

    Expects a CSV manifest with columns: cloud_path, gt_path
    Each .npy file contains a float32 array of shape (256, 256, 3) in [-1, 1].
    """

    def __init__(self, manifest_csv: str, base_dir: str = ".") -> None:
        """
        Args:
            manifest_csv: Path to a CSV file (train.csv, val.csv, or test.csv).
            base_dir: Root directory to resolve relative paths in the CSV.
        """
        self.base_dir = Path(base_dir)
        self.pairs: list[tuple[str, str]] = []

        with open(manifest_csv, "r", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                self.pairs.append((row["cloud_path"], row["gt_path"]))

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        """Load a single (cloudy, ground_truth) patch pair.

        Returns:
            cloud_tensor: Shape (3, 256, 256), float32, range [-1, 1].
            gt_tensor:    Shape (3, 256, 256), float32, range [-1, 1].
        """
        cloud_path, gt_path = self.pairs[idx]

        cloud_arr = np.load(cloud_path)   # (H, W, C)
        gt_arr = np.load(gt_path)         # (H, W, C)

        # HWC → CHW
        cloud_tensor = torch.from_numpy(cloud_arr.transpose(2, 0, 1)).float()
        gt_tensor = torch.from_numpy(gt_arr.transpose(2, 0, 1)).float()

        return cloud_tensor, gt_tensor


def build_dataloader(
    manifest_csv: str,
    batch_size: int = 16,
    shuffle: bool = True,
    num_workers: int = 2,
    base_dir: str = ".",
) -> DataLoader:
    """Build a single DataLoader from a CSV manifest.

    Args:
        manifest_csv: Path to the split CSV.
        batch_size: Batch size.
        shuffle: Whether to shuffle the dataset.
        num_workers: Number of data loading workers.
        base_dir: Root directory for resolving paths.

    Returns:
        Configured DataLoader.
    """
    dataset = CloudRemovalDataset(manifest_csv, base_dir=base_dir)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=True,
    )


def build_dataloaders(
    splits_dir: str,
    batch_size: int = 16,
    num_workers: int = 2,
    base_dir: str = ".",
) -> dict[str, DataLoader]:
    """Build train, val, and test DataLoaders from a splits directory.

    Args:
        splits_dir: Directory containing train.csv, val.csv, test.csv.
        batch_size: Batch size for all loaders.
        num_workers: Number of data loading workers.
        base_dir: Root directory for resolving paths.

    Returns:
        Dict with keys 'train', 'val', 'test' mapping to DataLoaders.
    """
    splits_path = Path(splits_dir)
    return {
        "train": build_dataloader(
            str(splits_path / "train.csv"), batch_size, shuffle=True,
            num_workers=num_workers, base_dir=base_dir,
        ),
        "val": build_dataloader(
            str(splits_path / "val.csv"), batch_size, shuffle=False,
            num_workers=num_workers, base_dir=base_dir,
        ),
        "test": build_dataloader(
            str(splits_path / "test.csv"), batch_size, shuffle=False,
            num_workers=num_workers, base_dir=base_dir,
        ),
    }
